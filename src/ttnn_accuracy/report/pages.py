def top_readme(data: dict) -> str:
    groups = {(a, d): group_by_display(data.get(a, {}).get(d, {})) for a in data for d in DTYPES}
    total_archs = len(data)
    total_ops = len(set().union(*(g.keys() for g in groups.values())))

    lines = [
        "# TT-Metal Eltwise Op Accuracy Reports\n\n",
        GENERATED_NOTE,
        "Accuracy measurements for TT-Metal elementwise operations vs PyTorch golden reference.\n",
        "Charts show ULP (units in last place) error across the full input range.\n\n",
        "---\n\n",
        "## Browse Reports\n\n",
        "| View | Description |\n",
        "|------|-------------|\n",
        "| [By Architecture](by_arch/README.md) | Start from hardware platform (WH, BH), then dtype, then op |\n",
        "| [By Operation](by_op/README.md) | Start from op name, compare across architectures and dtypes |\n",
        "| [By Data Type](by_dtype/README.md) | Start from bf16 or fp32, see all ops on all archs |\n",
        "\n---\n\n",
        "## Quick Stats\n\n",
        "| Metric | Count |\n",
        "|--------|-------|\n",
        f"| Architectures measured | {total_archs} |\n",
        f"| Unique ops measured | {total_ops} |\n",
    ]
    for arch in sorted(data):
        for dtype in DTYPES:
            if n := len(groups[arch, dtype]):
                lines.append(
                    f"| {ARCH_DISPLAY.get(arch, arch)} {DTYPE_DISPLAY.get(dtype, dtype)} ops | {n} |\n"
                )

    lines.extend(
        [
            "\n---\n\n",
            "## Data Collection\n\n",
            "```bash\n",
            "# Collect measurements (run on target hardware)\n",
            "ttnn-accuracy measure --arch wh --category unary --dtype both\n",
            "\n",
            "# Generate SVG charts and update report_index.json\n",
            "ttnn-accuracy charts\n",
            "\n",
            "# Regenerate this report tree\n",
            "ttnn-accuracy report\n",
            "```\n",
        ]
    )
    return "".join(lines)


def generate_reports(arch_filter=None, dtype_filter=None, categories=None) -> int:
    if categories is None:
        categories = ["unary"]

    data = discover_ops(categories=categories)

    # data carries an entry per arch/dtype directory even when every op was filtered out.
    if not any(ops for dtypes in data.values() for ops in dtypes.values()):
        logger.error(
            "no charts matched categories={} — run `ttnn-accuracy charts` first", categories
        )
        return 1

    archs = [arch_filter] if arch_filter else sorted(data)
    dtypes = [dtype_filter] if dtype_filter else DTYPES
    grouped = {(a, d): group_by_display(data.get(a, {}).get(d, {})) for a in archs for d in dtypes}

    write(REPORTS_DIR / "README.md", top_readme(data))

    write(REPORTS_DIR / "by_arch" / "README.md", arch_list_index(data))
    for arch in archs:
        write(REPORTS_DIR / "by_arch" / arch / "README.md", arch_index(arch, data.get(arch, {})))
        for dtype in dtypes:
            write(
                REPORTS_DIR / "by_arch" / arch / dtype / "README.md",
                arch_dtype_index(arch, dtype, data.get(arch, {}).get(dtype, {})),
            )
            for display_name, entries in grouped[arch, dtype].items():
                write(
                    REPORTS_DIR / "by_arch" / arch / dtype / f"{display_name}.md",
                    op_detail_page(arch, dtype, display_name, entries),
                )

    write(REPORTS_DIR / "by_op" / "README.md", op_list_index(data))
    for display_name in sorted(set().union(*(g.keys() for g in grouped.values()))):
        write(
            REPORTS_DIR / "by_op" / display_name / "README.md",
            op_cross_arch_page(display_name, data),
        )

    write(REPORTS_DIR / "by_dtype" / "README.md", dtype_list_index(data))
    for dtype in dtypes:
        write(REPORTS_DIR / "by_dtype" / dtype / "README.md", dtype_index(dtype, data))

    logger.success("report tree regenerated")
    return 0
